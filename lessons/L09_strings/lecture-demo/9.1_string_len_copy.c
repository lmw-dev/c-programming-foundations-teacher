/*
 * 文件名: 9.1_string_len_copy.c
 * 对应课件: 第09讲 PPT 第6, 7, 13, 14页【字符串本质、strlen vs sizeof 生死对决 & 安全复制】
 * 对应教材: 谭浩强版《C程序设计》第6章 例6.8, 6.9 + 何钦铭版《C语言程序设计》第5章
 * 适用环境: Visual Studio / Dev-C++ / VS Code
 * 
 * 核心教学目标:
 * 1. 掌握字符串在内存底层的物理存储结构及 '\0' (ASCII值为0) 结束哨兵的决定性作用
 * 2. 深度剖析 strlen (数货: 运行时有效字符数) 与 sizeof (量盒子: 编译时物理总字节数) 的本质区别
 * 3. 揭秘为什么不能直接写 dest = src (数组名是只读地址常量)，掌握手写安全复制与显式封口 '\0' 防御
 */

#include <stdio.h>
#include <string.h>

int main(void)
{
    printf("======================================================================\n");
    printf("     字符串底层探索 —— strlen vs sizeof 对决与手写安全复制实战         \n");
    printf("======================================================================\n\n");

    // =========================================================================
    // 【维度一：字符 'A' 对决字符串 "A" (物理内存字节占用)】
    // =========================================================================
    char char_a = 'A';
    char str_a[] = "A";

    printf("1. 【'A' vs \"A\" 物理内存解剖】:\n");
    printf("   单字符 'A'    : 占用 %lu 字节 (纯 ASCII 码 65)\n", sizeof(char_a));
    printf("   字符串 \"A\"    : 占用 %lu 字节 (物理由 'A' + 隐式 '\\0' 组成)\n\n", sizeof(str_a));

    // =========================================================================
    // 【维度二：strlen vs sizeof 生死对决 (数货 vs 量盒子)】
    // =========================================================================
    char src[20] = "C_Language";

    printf("2. 【strlen (数货) 与 sizeof (量盒子) 对决】:\n");
    printf("   源字符串内容 : \"%s\"\n", src);
    printf("   sizeof(src)  : %lu 字节 (量盒子: 整个字符数组在栈中开辟的总物理内存空间)\n", sizeof(src));
    printf("   strlen(src)  : %lu 字符 (数货  : 顺着内存扫描到 '\\0' 为止的实际有效字符数)\n\n", strlen(src));

    // =========================================================================
    // 【维度三：为什么不能直接写 dest = src？】
    // 语法天条:
    // 数组名 src 和 dest 是编译器确定的“地址常量 (只读指针)”，不能作为左值被赋值！
    // 必须通过逐字节搬家 (手写循环或 strcpy/strncpy) 来完成数据复制。
    // =========================================================================

    // =========================================================================
    // 【维度四：手写安全字符串截断复制 (防缓冲区溢出)】
    // 场景: 将长度为 10 的 src 复制到一个只能容纳 8 字节的小盒子 dest_small 中
    // =========================================================================
    char dest_small[8];
    size_t max_copy_len = sizeof(dest_small) - 1;  // 为末尾的 '\0' 死死留出 1 字节安全空间
    size_t i = 0;

    while (i < max_copy_len && src[i] != '\0')
    {
        dest_small[i] = src[i];  // 逐字节物理搬家
        i++;
    }
    dest_small[i] = '\0';  // 🚨 黄金铁律: 必须在末尾显式手工封口贴上 '\0' 哨兵！

    printf("3. 【手写安全截断复制演示 (防爆仓)】:\n");
    printf("   小盒子容量限制 : %lu 字节 (最大接收 7 字符 + 1 字节 '\\0')\n", sizeof(dest_small));
    printf("   安全截断复制结果: \"%s\" (有效长度: %lu)\n\n", dest_small, strlen(dest_small));

    // 4. 足量大盒子的完整复制演示
    char dest_safe[20];
    strcpy(dest_safe, src);
    printf("4. 【标准库 strcpy 完整复制演示】:\n");
    printf("   dest_safe 内容 : \"%s\" (strlen: %lu, sizeof: %lu)\n", 
           dest_safe, strlen(dest_safe), sizeof(dest_safe));

    printf("\n============================ 教学避坑总结 ============================\n");
    printf("💡 为什么忘记加 '\\0' 会出现“烫烫烫”乱码？\n");
    printf("   因为 printf(\"%%s\") 打印时在数组边界内找不到 '\\0' 刹车片，会继续在相邻栈内存裸奔，\n");
    printf("   将未初始化的栈填充字节 (0xCCCC) 强行解码为字符，产生著名的中文“烫”字乱码！\n");
    printf("======================================================================\n");

    return 0;
}
