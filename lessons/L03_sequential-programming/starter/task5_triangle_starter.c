/*
 * 任务 5 起步模板：三角形面积测量仪 (何版经典·海伦公式)
 * 对应课件: 第03讲 PPT 第26页【实操大满贯·任务五：三角形面积测量仪】
 * 适用环境: Visual Studio 2022 / Dev-C++ / VS Code
 * 
 * 任务说明:
 * 1. 引入数学库头文件 <math.h>
 * 2. 从键盘读入三角形三边长 a, b, c (double 类型)
 * 3. 🚨 防坑天条: 计算半周长 s 时必须除以 2.0 (s = (a + b + c) / 2.0)，严禁除以整数 2！
 * 4. 调用 sqrt() 函数根据海伦公式计算面积:
 *    area = sqrt(s * (s - a) * (s - b) * (s - c))
 * 5. 使用 %.2f 格式化保留两位小数输出
 */

#define _CRT_SECURE_NO_WARNINGS

#include <stdio.h>
#include <math.h> // TODO 1: 引入 math.h

int main(void)
{
    printf("====================================================\n");
    printf("     【任务五】三角形面积测量仪 (海伦公式)          \n");
    printf("====================================================\n\n");

    double a = 0.0, b = 0.0, c = 0.0;

    printf("请输入三角形的三边长 a b c (空格隔开，例如 3.0 4.0 5.0): ");
    if (scanf("%lf %lf %lf", &a, &b, &c) != 3 || a <= 0.0 || b <= 0.0 || c <= 0.0) {
        printf("⚠️ 输入错误: 边长必须为正数！\n");
        return 1;
    }

    // 三角形构成条件判定
    if (a + b <= c || a + c <= b || b + c <= a) {
        printf("⚠️ 几何错误: 任意两边之和必须大于第三边，无法构成三角形！\n");
        return 1;
    }

    // TODO 2: 计算半周长 s (强制除以 2.0 浮点数，避开整除截断)
    double s = (a + b + c) / 2.0;

    // TODO 3: 调用 sqrt() 计算海伦公式面积
    double area = sqrt(s * (s - a) * (s - b) * (s - c));

    printf("\n---------------- 三角形面积测量报告 ----------------\n");
    printf("  * 输入边长 a, b, c : %.2f, %.2f, %.2f\n", a, b, c);
    printf("  * 半周长 s         : %.2f\n", s);
    printf("  * 三角形面积 (Area): %.2f 平方单位\n", area);
    printf("----------------------------------------------------\n\n");

    return 0;
}
