// =============================================================================
// 案例 3-3：自增自减与短路求值电路模型 (PPT 第6、8页)
// =============================================================================
void run_case_3_3(void)
{
    printf("\n======================================================================\n");
    printf("   【案例 3-3】自增自减内存动作与短路求值电路模型 (PPT 第6、8页)        \n");
    printf("======================================================================\n\n");

    // 1. 前置与后置自增
    int i1 = 3, j1;
    j1 = ++i1; // 前置：先加后用
    printf("[实验 1] 前置自增 (i = 3; j = ++i;):\n");
    printf("  -> i 变为 %d, j 得到 %d (先加为4，再传给j)\n\n", i1, j1);

    int i2 = 3, j2;
    j2 = i2++; // 后置：先用后加
    printf("[实验 2] 后置自增 (i = 3; j = i++;):\n");
    printf("  -> i 变为 %d, j 得到 %d (先传3给j，i再加为4)\n\n", i2, j2);

    // 2. 短路求值电路模型
    int a = 0, b = 1, c;
    c = a++ && (b = 3); // 逻辑与短路！
    printf("[实验 3] 逻辑与短路实验 (a = 0, b = 1; c = a++ && (b = 3);):\n");
    printf("  -> 执行结果: a = %d, b = %d, c = %d\n", a, b, c);
    printf("  -> 原理解析: a++ 逻辑值为假(0)，触发逻辑与短路，右侧 (b = 3) 被完全掐断！\n");
    printf("======================================================================\n");
}

// =============================================================================
// 案例 3-4：多重存款利息计算器三种方式对比 (PPT 第21页 谭版例3.2)
// =============================================================================
void run_case_3_4(void)
{
    printf("\n======================================================================\n");
    printf("   【案例 3-4】多重存款利息计算器三种方式对比 (PPT 第21页 谭版例3.2)    \n");
    printf("======================================================================\n\n");

    float p0 = 1000.0f; // 初始本金 1000 元
    float r1 = 0.0036f; // 活期年利率 0.36%
    float r2 = 0.0225f; // 一年定期年利率 2.25%
    float r3 = 0.0198f; // 半年定期年化利率 1.98%

    float p1 = p0 * (1.0f + r1);                              // 活期本息和
    float p2 = p0 * (1.0f + r2);                              // 一年定期本息和
    float p3 = p0 * (1.0f + r3 / 2.0f) * (1.0f + r3 / 2.0f); // 两次半年定期连存本息和

    printf("本金: %.2f 元, 存期: 1 年\n", p0);
    printf("--------------------------------------------------\n");
    printf("方案 1 (活期存款)          : 到期本息和 = %10.5f 元\n", p1);
    printf("方案 2 (一年定期)          : 到期本息和 = %10.5f 元 (最高收益!)\n", p2);
    printf("方案 3 (两次半年定期连存)  : 到期本息和 = %10.5f 元 (复利滚动)\n", p3);
    printf("--------------------------------------------------\n");
    printf("【财务分析】: 方案2定期存款收益最高；方案3虽有利滚利，但基准利率偏低仍不及方案2。\n");
    printf("======================================================================\n");
}

