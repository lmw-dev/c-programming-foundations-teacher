// =============================================================================
// 案例 3-1：华氏度转摄氏度与 5/9 截断排雷 (PPT 第19页)
// =============================================================================
void run_case_3_1(void)
{
    printf("\n======================================================================\n");
    printf("   【案例 3-1】华氏温度转摄氏温度与 5/9 整除截断排雷 (PPT 第19页)       \n");
    printf("======================================================================\n\n");

    float fahrenheit = 100.0f;
    float celsius_wrong = 0.0f;
    float celsius_correct = 0.0f;

    printf("[思考实验] 设华氏温度 fahrenheit = %.2f °F\n\n", fahrenheit);

    // 1. 错误计算：5 / 9 整除截断为 0
    celsius_wrong = (5 / 9) * (fahrenheit - 32.0f);
    printf("[陷阱诊断 1] 错误写法: c = (5 / 9) * (f - 32.0f);\n");
    printf("  -> 错误计算结果: %.2f °C (程序被“冻结”为零!)\n", celsius_wrong);
    printf("  -> 物理天条剖析: 5 和 9 均为整数，5 / 9 执行整除，小数直接被截断为 0！\n\n");

    // 2. 正确计算：5.0f / 9.0f 浮点除法
    celsius_correct = (5.0f / 9.0f) * (fahrenheit - 32.0f);
    printf("[黄金治愈 2] 正确写法: c = (5.0f / 9.0f) * (f - 32.0f);\n");
    printf("  -> 正确计算结果: %.2f °C\n", celsius_correct);
    printf("  -> 避坑口诀: 算除法，留心眼；分子分母带点零 (.0)，小数精度不丢失！\n");
    printf("======================================================================\n");
}

