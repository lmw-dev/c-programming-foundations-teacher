#define _CRT_SECURE_NO_WARNINGS

#include <stdio.h>
#include <math.h>

int main(void)
{
    printf("====================================================\n");
    printf("  【任务五 参考答案】三角形面积测量仪 (PPT 第26页)   \n");
    printf("====================================================\n\n");

    double a = 0.0, b = 0.0, c = 0.0;

    printf("请输入三角形的三边长 a b c (例如 3.0 4.0 5.0): ");
    if (scanf("%lf %lf %lf", &a, &b, &c) != 3 || a <= 0.0 || b <= 0.0 || c <= 0.0) {
        printf("⚠️ 输入错误！\n");
        return 1;
    }

    if (a + b <= c || a + c <= b || b + c <= a) {
        printf("⚠️ 几何错误: 无法构成三角形！\n");
        return 1;
    }

    // 核心排雷: 强制除以 2.0 浮点数，避开整除截断
    double s = (a + b + c) / 2.0;
    double area = sqrt(s * (s - a) * (s - b) * (s - c));

    printf("\n---------------- 三角形面积测量报告 ----------------\n");
    printf("  * 输入边长 a, b, c : %.2f, %.2f, %.2f\n", a, b, c);
    printf("  * 半周长 s         : %.2f\n", s);
    printf("  * 三角形面积 (Area): %.2f 平方单位\n", area);
    printf("----------------------------------------------------\n\n");

    printf("【考点剖析】: 在除法公式中分母必须写成浮点数（如 2.0），防止被整除截断抹去小数。\n");
    printf("====================================================\n");

    return 0;
}
