#define _CRT_SECURE_NO_WARNINGS

#include <stdio.h>
#include <math.h>

int main(void)
{
    printf("====================================================\n");
    printf("  【任务二 参考答案】购房还贷月数预算师 (PPT 第23页) \n");
    printf("====================================================\n\n");

    double d = 0.0;
    double p = 0.0;
    double r = 0.0;

    printf("请输入贷款总额 d、每月还款额 p、月利率 r (如 300000 6000 0.005): ");
    if (scanf("%lf %lf %lf", &d, &p, &r) != 3 || d <= 0.0 || p <= 0.0 || r <= 0.0) {
        printf("⚠️ 输入错误！\n");
        return 1;
    }

    if (p <= d * r) {
        printf("⚠️ 错误: 每月还款额必须大于利息支出 (%.2f)！\n", d * r);
        return 1;
    }

    // 核心对数公式
    double m_real = (log10(p) - log10(p - d * r)) / log10(1.0 + r);
    // 向上取整计算实际需要归还的整月数
    int m_months = (int)ceil(m_real);

    printf("\n---------------- 还款计划预算报告 ----------------\n");
    printf("  * 贷款总额 (d)   : %12.2f 元\n", d);
    printf("  * 每月月供 (p)   : %12.2f 元\n", p);
    printf("  * 银行月利率 (r) : %11.2f %%\n", r * 100.0);
    printf("  ------------------------------------------------\n");
    printf("  * 理论计算月数   : %12.2f 个月\n", m_real);
    printf("  * 实际还清月数   : %12d 个月 (向上取整)\n", m_months);
    printf("--------------------------------------------------\n\n");

    printf("【考点剖析】: 掌握 <math.h> 中 log10() 与 ceil() 向上取整函数的实战运用。\n");
    printf("====================================================\n");

    return 0;
}
