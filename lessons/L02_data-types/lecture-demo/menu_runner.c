// 案例 2-2：整型补码与 20000+20000 溢出实验 (PPT 第14~15页)
// =============================================================================
void run_case_2_2(void)
{
    printf("\n======================================================================\n");
    printf("   【案例 2-2】整型值域与 20000+20000 溢出陷阱 (PPT 第14~15页)        \n");
    printf("======================================================================\n\n");

    int a = 20000, b = 20000, c;
    c = a + b;

    printf("[思考题] int a = 20000, b = 20000, c = a + b;\n");
    printf("  -> 当前 32/64 位现代系统 (int 占 4 字节, ±21亿): c = %d (正常)\n\n", c);

    printf("[物理底层深度剖析: 16位嵌入式系统/旧版 Turbo C]:\n");
    printf("  -> 16位 signed int 范围: -32768 ~ +32767\n");
    printf("  -> 40000 超出上限发生【整型溢出】！最高位变为1，溢出成了负数: -25536\n\n");

    printf("[正确改法演示]:\n");
    long long safe_c1 = (long long)a + b; // 强制类型转换，计算提升为 64 位
    printf("  -> 改法 1 (强制类型转换提升): c = (long long)a + b  --> %lld\n", safe_c1);
    long long big_a = 20000LL, big_b = 20000LL;
    printf("  -> 改法 2 (声明高规格数据类型): long long big_a, big_b --> %lld\n", big_a + big_b);
    printf("======================================================================\n");
}

