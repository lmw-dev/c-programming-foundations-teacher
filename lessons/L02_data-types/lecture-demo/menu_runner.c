// 案例 2-4：凯撒密码单字偏移与 ASCII 进制密电 (PPT 第17、21页)
// =============================================================================
void run_case_2_4(void)
{
    printf("\n======================================================================\n");
    printf("   【案例 2-4】凯撒密码单字偏移与 ASCII 进制密电 (PPT 第17、21页)      \n");
    printf("======================================================================\n\n");

    // 1. 转义字符进制密电还原
    char c1 = '\101'; // 八进制形式
    char c2 = '\x41'; // 十六进制形式
    printf("[实验 1] 转义字符密电还原 (八进制 '\\101' & 十六进制 '\\x41'):\n");
    printf("  -> c1 ('\\101') = '%c' (十进制ASCII: %d)\n", c1, c1);
    printf("  -> c2 ('\\x41') = '%c' (十进制ASCII: %d)\n", c2, c2);
    printf("  -> 核心结论: 'A' == '\\101' == '\\x41' == 65，底层完全等价！\n\n");

    // 2. 凯撒密码单字偏移
    char raw_char = 'C';
    char secret_char = raw_char + 3;
    printf("[实验 2] 凯撒密码单字偏移器 (以字母 '%c' 为例):\n", raw_char);
    printf("  -> 原字符: '%c' (ASCII值: %d)\n", raw_char, raw_char);
    printf("  -> 加密后 (raw_char + 3): '%c' (ASCII值: %d)\n", secret_char, secret_char);
    printf("  -> 物理本质: char 就是 1 字节整数，可以直接进行加减数学运算！\n");
    printf("======================================================================\n");
}

