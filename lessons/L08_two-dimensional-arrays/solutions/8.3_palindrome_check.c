/*
 * 文件名: 8.3_palindrome_check.c
 * 对应课件: 第08讲 PPT 第17~19页【阶段复习与综合案例：判断回文字符串 & 字符串结束符 '\0'】
 * 对应教材: 谭浩强版《C程序设计》第6章 例6.8 + 何钦铭版《C语言程序设计》第5章
 * 适用环境: Visual Studio / Dev-C++ / VS Code
 * 
 * 核心教学目标:
 * 1. 掌握字符数组在内存中的物理存储，以及字符串隐式结束符 '\0' (ASCII值为0) 的关键作用
 * 2. 掌握双指针向心逼近对碰算法 (Two-pointer Meeting): left 从 0 递增，right 从 len-1 递减
 * 3. 掌握防御性字符串输入 scanf("%99s", str) 防止缓冲区溢出 (Buffer Overflow)
 */

#include <stdio.h>
#include <string.h>

#define MAX_LEN 100

int main(void)
{
    printf("======================================================================\n");
    printf("     阶段综合实战 —— 字符数组、'\\0' 哨兵与双指针向心回文判定           \n");
    printf("======================================================================\n\n");

    char str[MAX_LEN];
    int is_palindrome = 1;  // 标志变量：1 代表是回文，0 代表不是回文

    // 1. 安全读取字符串 (利用 %99s 强制限制最多读 99 个字符，为末尾 '\0' 预留空间)
    printf("👉 请输入一个英文单词或字符串 (最大99字符, 如 radar, level, noon): ");
    if (scanf("%99s", str) != 1) {
        printf("⚠️ 输入无效！\n");
        return 1;
    }

    // =========================================================================
    // 【物理测长机制解析】
    // 
    // strlen(str) 的底层工作原理:
    // 从 str[0] 开始逐字节扫描，遇到 '\0' 时立即停止并返回前面字符的总个数。
    // ⚠️ 警示: 如果字符数组末尾丢失了 '\0'，printf("%s") 与 strlen() 将会冲出数组边界，
    // 在相邻的公共栈内存中持续裸奔，导致输出著名的中文“烫烫烫”乱码 (0xCCCC 填充字节)！
    // =========================================================================
    int length = 0;
    while (str[length] != '\0')
    {
        length++;  // 手动寻找 '\0' 哨兵测长
    }

    printf("\n1. 【字符串物理属性检测】:\n");
    printf("   有效字符长度 (Length) : %d\n", length);
    printf("   数组占用总内存 (Size)  : %lu 字节\n", sizeof(str));
    printf("   末尾哨兵字符 '\\0' 验证: str[%d] 的 ASCII 码值为 %d\n\n", length, (int)str[length]);

    // =========================================================================
    // 【核心算法：双指针向心对碰判定 (Two-pointer Meeting)】
    // 
    // 物理轨迹:
    //   首指针 left = 0，尾指针 right = length - 1
    //   当 left < right 时:
    //     - 若 str[left] != str[right]，一票否决，is_palindrome = 0 并 break 退出；
    //     - 若相等，left 往右走 (left++)，right 往左走 (right--)，继续向中心聚拢。
    // =========================================================================
    int left = 0;
    int right = length - 1;

    while (left < right)
    {
        if (str[left] != str[right])
        {
            is_palindrome = 0;  // 发现不匹配，推翻假设
            break;              // 提前制动，跳出判定循环
        }
        left++;
        right--;
    }

    // 2. 输出最终判定报告
    printf("----------------------------------------------------------------------\n");
    printf("2. 【回文检测判定结论】:\n");
    if (is_palindrome == 1)
    {
        printf("  🎉 恭喜！字符串 \"%s\" 是完美的【回文字符串】！(正读反读完全一致)\n", str);
    }
    else
    {
        printf("  ❌ 遗憾！字符串 \"%s\" 不是回文字符串。\n", str);
    }
    printf("======================================================================\n");

    return 0;
}
