/*
 * 文件名: 8.1_matrix_transpose.c
 * 对应课件: 第08讲 PPT 第5, 8页【内存剖析：行优先线性存储真相 & 矩阵转置算法】
 * 对应教材: 谭浩强版《C程序设计》第6章 例6.4 + 何钦铭版《C语言程序设计》第5章
 * 适用环境: Visual Studio / Dev-C++ / VS Code
 * 
 * 核心教学目标:
 * 1. 彻底击碎“二维平面网格内存”假象，通过打印十六进制物理内存地址 (%p)，
 *    向学生证明二维数组在底层是一条完全线性的“行优先存储 (Row-Major Order)”序列。
 * 2. 掌握矩阵转置算法物理映射机制：b[j][i] = a[i][j] (原 a 的第 i 行 j 列放入 b 的第 j 行 i 列)。
 * 3. 揭秘为什么声明二维数组时第二维 (列数) 绝对不能省略：
 *    编译器计算物理寻址公式为：Address = Base + (i * Columns + j) * sizeof(type)。
 */

#include <stdio.h>

#define ROWS_A 2
#define COLS_A 3

int main(void)
{
    printf("======================================================================\n");
    printf("      二维数组深度探索 —— 物理内存线性验证 (%p) 与矩阵转置算法          \n");
    printf("======================================================================\n\n");

    // 1. 声明并初始化 2x3 的整型矩阵 a
    int matrix_a[ROWS_A][COLS_A] = {
        {1, 2, 3},
        {4, 5, 6}
    };

    // 2. 准备接收转置结果的 3x2 空矩阵 b
    int matrix_b[COLS_A][ROWS_A];

    // =========================================================================
    // 【物理内存连续性验证 (Row-Major Order)】
    // 观察: 打印各个元素的内存地址，证明第 0 行末尾元素 matrix_a[0][2] 
    // 与第 1 行首元素 matrix_a[1][0] 在内存地址上是严格相邻的 (相差 sizeof(int)=4 字节)！
    // =========================================================================
    printf("1. 【原矩阵 matrix_a (2行3列) 物理内存地址巡检】:\n");
    for (int i = 0; i < ROWS_A; i++)
    {
        for (int j = 0; j < COLS_A; j++)
        {
            printf("   matrix_a[%d][%d] = %d | 物理内存地址: %p\n", 
                   i, j, matrix_a[i][j], (void*)&matrix_a[i][j]);
        }
    }

    // =========================================================================
    // 【核心转置算法 (Matrix Transposition)】
    // 物理映射: 双重循环外层遍历原矩阵行 i，内层遍历原矩阵列 j
    // 搬家指令: matrix_b[j][i] = matrix_a[i][j]
    // =========================================================================
    for (int i = 0; i < ROWS_A; i++)
    {
        for (int j = 0; j < COLS_A; j++)
        {
            matrix_b[j][i] = matrix_a[i][j];
        }
    }

    // 3. 格式化网格输出原矩阵与转置后的矩阵
    printf("\n----------------------------------------------------------------------\n");
    printf("2. 【原矩阵 a 网格视图 (2x3)】:\n");
    for (int i = 0; i < ROWS_A; i++)
    {
        printf("   │ ");
        for (int j = 0; j < COLS_A; j++)
        {
            printf("%4d ", matrix_a[i][j]);
        }
        printf("│\n");
    }

    printf("\n3. 【转置后矩阵 b 网格视图 (3x2)】:\n");
    for (int i = 0; i < COLS_A; i++)
    {
        printf("   │ ");
        for (int j = 0; j < ROWS_A; j++)
        {
            printf("%4d ", matrix_b[i][j]);
        }
        printf("│\n");
    }

    printf("\n============================ 教学原理解析 ============================\n");
    printf("💡 为什么定义二维数组时“列数”绝对不能省略（如 int a[][3] 可以，int a[2][] 必报错）？\n");
    printf("   因为编译器要将二维下标 [i][j] 降维映射成一维线性内存，必须使用列数 (Columns) 做乘法：\n");
    printf("   物理偏移量 Offset = (i * Columns + j) * sizeof(int)\n");
    printf("   如果省略了列数，编译器根本不知道每一行跨越几个隔间，寻址系统就会彻底瘫痪！\n");
    printf("======================================================================\n");

    return 0;
}
