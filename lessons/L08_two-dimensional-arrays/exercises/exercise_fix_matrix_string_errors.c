/*
 * 练习题：二维数组与字符数组阶段排雷改错实战 (阶段回收节点 1)
 * 对应课件: 第08讲 PPT 第6, 11, 15页【避坑指南：多重嵌套循环与字符数组三大雷区】
 * 
 * 题目要求:
 * 观察并修复下方代码中的 3 处经典逻辑与越界漏洞：
 * 漏洞 1: 声明二维数组时非法省略了第二维（列数）
 * 漏洞 2: 嵌套循环行与列边界张冠李戴（遍历时行循环超出上限越界）
 * 漏洞 3: 字符数组定义长度刚好等于字符数，导致丢失字符串结束符 '\0' 引发乱码
 */

#include <stdio.h>

int main(void)
{
    printf("=== 二维数组与字符串阶段排雷 ===\n");

    // 修复点 1: 第二维（列数 3）绝对不能省略，第一维（行数 2）可以省略
    int matrix[][3] = {
        {10, 20, 30},
        {40, 50, 60}
    };

    // 修复点 2: 外层行必须是 i < 2，内层列必须是 j < 3 (严防行列张冠李戴)
    printf("矩阵内容:\n");
    for (int i = 0; i < 2; i++)
    {
        for (int j = 0; j < 3; j++)
        {
            printf("%4d ", matrix[i][j]);
        }
        printf("\n");
    }

    // 修复点 3: 容纳 "C++" (3个字符) 必须分配至少 4 个字节，为隐式 '\0' 预留空间
    char msg[4] = "C++";
    printf("字符串安全输出: %s (长度为 3, 内存占 4 字节)\n", msg);

    return 0;
}
