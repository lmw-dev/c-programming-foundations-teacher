/*
 * 文件名: 1.1_hello_world.c
 * 对应课件: 第01讲 PPT 第5~6页【一个C程序长什么样 & 程序的基本构成】
 * 对应教材: 第1章 C语言概述 + 第3章 顺序程序设计(起步)
 * 描述: 最简单的标准 C 语言程序，用于课堂演示与逐行剖析
 * 适用: C语言零基础初学者
 * 
 * 核心知识点:
 * 1. 预处理指令：#include <stdio.h> 引入标准输入输出库
 * 2. 主函数声明：int main(void) 是所有 C 程序的唯一入口
 * 3. 函数体边界：花括号 { } 框定执行语句的范围
 * 4. 格式化输出：printf() 函数输出双引号内的文本
 * 5. 转义换行符：\n 将光标移动到下一行首
 * 6. 语句结束符：英文分号 ';' 是每条语句的法定结束标志
 * 7. 正常返回：return 0; 向操作系统返回执行成功状态码
 */

// ① 预处理指令：引入标准输入输出头文件 (standard input output header)
// 引入后程序才能识别并调用 printf 等库函数
#include <stdio.h>

// ② 主函数：操作系统调用程序的起点（入口门牌号）
// int: 函数返回值类型为整数 (Integer)
// (void): 表示该主函数不接收任何来自外部的命令行参数（教材推荐标准写法）
int main(void)
{
    // ③ 输出语句：向标准输出（屏幕控制台）打印双引号中的文本
    // \n 是换行转义字符（注意是反斜杠 '\'，非正斜杠 '/'）
    // 语句末尾必须以英文半角分号 ';' 结尾
    printf("Hello, C!\n");

    // ④ 返回语句：向操作系统汇报程序正常结束
    // 0 通常表示程序顺利完成，无异常退出
    return 0;
}
