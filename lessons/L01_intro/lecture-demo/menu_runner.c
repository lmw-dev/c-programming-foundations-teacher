// 案例 1-0：极简 7 条 CPU 指令系统与程序本质模拟器 (PPT 第10~12页)
// =============================================================================
void run_case_1_0(void)
{
    printf("\n======================================================================\n");
    printf("   【案例 1-0】极简虚拟 CPU 指令模拟器 (PPT 第10~12页)                \n");
    printf("======================================================================\n\n");

    printf("▶ 演示 1：顺序指令序列计算 A + B + C (设 A=3, B=5, C=8)\n");
    int mem_A = 3, mem_B = 5, mem_C = 8, mem_D = 0;

    printf("  [指令 1~3] Input A, B, C    --> A=%d, B=%d, C=%d\n", mem_A, mem_B, mem_C);
    mem_D = mem_A + mem_B;
    printf("  [指令 4]   Add A B D        --> D = A + B = %d\n", mem_D);
    mem_D = mem_C + mem_D;
    printf("  [指令 5]   Add C D D        --> D = C + D = %d\n", mem_D);
    printf("  [指令 6]   Output D         --> 最终累加和: %d\n\n", mem_D);

    printf("▶ 演示 2：循环与判断指令模拟 A * B (设 A=6, B=4，即 6 累加 4 次)\n");
    int A = 6, B = 4, X = 0, Z = 0;
    int step = 0;
    while (1)
    {
        step++;
        printf("  [循环第 %d 轮] BranchEq X B (当前计数 X=%d, 目标 B=%d)\n", step, X, B);
        if (X == B)
        {
            printf("  --> 判定成功: 达到 %d 次，跳出循环！\n", B);
            break;
        }
        Z += A;
        X += 1;
        printf("      Add Z A Z (Z变为 %d) | Add X 1 X (X变为 %d) | Jump 5\n", Z, X);
    }
    printf("  [指令 9]   Output Z         --> 最终乘积: %d * %d = %d\n", A, B, Z);
    printf("======================================================================\n");
}

