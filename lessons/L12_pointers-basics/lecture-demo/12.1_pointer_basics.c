/*
 * 文件名: 12.1_pointer_basics.c
 * 对应课件: 第12讲 PPT 第4, 5, 6, 7, 9, 10页【特工008寻宝游戏：指针基础、&与*及NULL防御】
 * 对应教材: 谭浩强版《C程序设计》第8章 8.1, 8.2 + 北京石油化工学院《C语言程序设计》第8章
 * 适用环境: Visual Studio / Dev-C++ / VS Code
 * 
 * 核心教学目标:
 * 1. 建立指针物理模型：变量（保险箱金币）、地址（门牌号）、指针变量（记录门牌号的纸条收纳盒）
 * 2. 熟练掌握“黑白双煞”运算符：& 取地址符（获取门牌号）与 * 间接访问/解引用符（砸开大门取值改值）
 * 3. 掌握“隔空打牛”间接改值技术：通过 *agent_ptr = 555 物理改写原始变量
 * 4. 深刻认识野指针（Wild Pointer）危害，建立“初始化为 NULL + 读写前判空”的工业安全防线
 */

#include <stdio.h>

int main(void)
{
    printf("======================================================================\n");
    printf("    特工 008 寻宝行动 —— C语言指针物理内存解剖与间接控制实战            \n");
    printf("======================================================================\n\n");

    // =========================================================================
    // 【第 1 幕：目标变量（龙井号保险箱里的金币）】
    // =========================================================================
    int safe_box = 911;

    printf("1. 【目标变量物理状态 (Direct Access)】:\n");
    printf("   【宝物值 (Value)】    safe_box  = %d\n", safe_box);
    printf("   【物理地址 (Address)】 &safe_box = %p (内存中专属的十六进制门牌号)\n\n", (void*)&safe_box);

    // =========================================================================
    // 【第 2 幕：指针变量（虎跑号寄存箱里的情报纸条）】
    // 语法: int *agent_ptr = &safe_box;
    // 💡 声明中的 '*' 是类型印章，表示 agent_ptr 是一个专门装整型地址的指针变量！
    // =========================================================================
    int *agent_ptr = &safe_box;

    printf("2. 【指针变量物理状态 (Pointer Variable)】:\n");
    printf("   【指针装载的地址值】  agent_ptr  = %p (指向 safe_box 的门牌号)\n", (void*)agent_ptr);
    printf("   【指针自身的物理地址】&agent_ptr = %p (纸条自身也躺在另一块内存单元里)\n", (void*)&agent_ptr);
    printf("   【解引用获取宝物值】 *agent_ptr = %d (拿钥匙砸开大门，提取出宝物 911)\n\n", *agent_ptr);

    // =========================================================================
    // 【第 3 幕：隔空打牛 —— 间接修改目标变量的值】
    // =========================================================================
    printf("3. 【执行间接修改: *agent_ptr = 555】:\n");
    *agent_ptr = 555; // 顺着纸条上的地址，直接潜入 safe_box 内部掉包金币

    printf("   🎯 巡检目标变量 safe_box 的当前值: %d\n", safe_box);
    printf("   💡 结论: 在没有任何 direct 赋值 (如 safe_box = ...) 的前提下，\n");
    printf("           通过指针解引用 (*agent_ptr = 555) 成功完成了物理内存的原地篡改！\n\n");

    // =========================================================================
    // 【第 4 幕：野指针防空警报与 NULL 安全防御隔离区】
    // =========================================================================
    printf("4. 【工业级安全防御：严防无主野指针 (Wild Pointer)】:\n");

    /*
     * 🚨 致命反面教材（禁止在未初始化时强行解引用）：
     * int *dangerous_ptr; // 局部指针变量未初始化，里面是随机垃圾门牌号 (如 0xCCCCCCCC)
     * *dangerous_ptr = 999; // 💥 致命崩溃！私闯操作系统核心保护禁区，触发段错误 (Segmentation Fault) 闪退！
     */

    // ✅ 工业级规范：若指针暂时没有明确目标，必须初始化为 NULL (物理 0 号地址)
    int *safe_ptr = NULL;

    printf("   已声明空指针: safe_ptr = %p (安全哨兵)\n", (void*)safe_ptr);

    // 读写前执行防御性判空拦截
    if (safe_ptr != NULL)
    {
        *safe_ptr = 100;
    }
    else
    {
        printf("   🛡️ 【安全防御拦截】检测到 safe_ptr 为 NULL，成功阻止了野针裸奔越界修改引发的系统崩溃！\n");
    }

    printf("\n======================================================================\n");
    return 0;
}
