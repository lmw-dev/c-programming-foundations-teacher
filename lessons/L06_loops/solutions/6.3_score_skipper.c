/*
 * 文件名: 6.3_score_skipper.c
 * 对应课件: 第06讲 PPT 第11~15页【break 与 continue 深度实战 & 及格成绩过滤器】
 * 对应教材: 谭浩强版《C程序设计》第5章 例5.4~5.6 + 何钦铭版《C语言程序设计》第4章
 * 适用环境: Visual Studio / Dev-C++ / VS Code
 * 
 * 核心教学目标:
 * 1. 深度对比 break（直接退赛，队伍解散）与 continue（本次免谈，下位继续）的控制流物理跳转
 * 2. 揭秘专升本金牌地雷：在 while 中使用 continue 会抄近路跳过 i++ 导致死循环
 * 3. 掌握交互式数据过滤、哨兵退出 (-1) 与及格率统计业务流
 */

#include <stdio.h>

int main(void)
{
    printf("====================================================\n");
    printf("     教务成绩质检系统 —— break 与 continue 实战     \n");
    printf("====================================================\n\n");

    float score = 0.0f;
    float sum_score = 0.0f;
    int total_valid_count = 0;
    int pass_count = 0;

    printf("💡 录入规则: 请依次输入学生成绩 (0~100分)，输入 -1 结束录入。\n\n");

    // =========================================================================
    // 【无限循环架构：结合 break 与 continue 精细控制】
    // =========================================================================
    while (1)
    {
        printf("请输入成绩: ");
        if (scanf("%f", &score) != 1) {
            printf("⚠️ 输入格式错误，终止录入！\n");
            break;
        }

        // =====================================================================
        // 【控制流动作 1：break 紧急制动】
        // 当输入哨兵值 -1 时，无条件斩断整条 while 循环，立刻跳出大括号！
        // =====================================================================
        if (score == -1.0f)
        {
            printf("🛑 检测到退出哨兵值 -1，结束成绩录入。\n\n");
            break;  // 降落点: 直接跳出 while 循环体！
        }

        // =====================================================================
        // 【控制流动作 2：continue 局部越档过滤】
        // 当输入异常成绩（负数或超过100分）时，忽略本次数据，不计入统计，直奔下一轮！
        // =====================================================================
        if (score < 0.0f || score > 100.0f)
        {
            printf("⚠️ [警告] 异常成绩 %.1f 无效！已通过 continue 跳过，请重新输入！\n", score);
            continue;  // 降落点: 跳过下方累加语句，直接回到 while 头部重新开始！
        }

        // 3. 正常数据业务统计
        sum_score += score;
        total_valid_count++;

        if (score >= 60.0f)
        {
            pass_count++;
        }
    }

    // =========================================================================
    // 【死循环深度警示区 (Vocational Exam Trap)】
    // ⚠️ 极其危险的错误写法:
    // 如果在普通带计数器的 while 循环中写了 continue:
    // int i = 1;
    // while (i <= 10) {
    //     if (i == 3) continue; // ❌ 致命！直接跳回 while(i<=10)，下面的 i++ 被跳过！
    //     printf("%d", i);      // i 永远被冻结在 3，系统当场死循环卡死！
    //     i++;
    // }
    // 💡 避坑法则: 在 for 循环中 continue 会安全跳至 表达式3 (i++)；但在 while 中使用 continue 前必须手动先写 i++！
    // =========================================================================

    // 4. 统计结果输出
    printf("==================== 成绩统计报告 ====================\n");
    printf("  有效录入人数 (Count)     : %d 人\n", total_valid_count);
    if (total_valid_count > 0)
    {
        float average = sum_score / (float)total_valid_count;
        float pass_rate = ((float)pass_count / (float)total_valid_count) * 100.0f;

        printf("  及格总人数 (Passed)      : %d 人\n", pass_count);
        printf("  班级及格率 (Pass Rate)   : %.2f %%\n", pass_rate);
        printf("  班级平均分 (Average)     : %.2f 分\n", average);
    }
    else
    {
        printf("  提示: 未录入任何有效成绩。\n");
    }
    printf("======================================================\n");

    return 0;
}
