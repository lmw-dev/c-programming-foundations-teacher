/*
 * 文件名: 6.1_multiplication_table.c
 * 对应课件: 第06讲 PPT 第9~10页【何版经典案例：九九乘法表的行列奥秘】
 * 对应教材: 谭浩强版《C程序设计》第5章 例5.8 + 何钦铭版《C语言程序设计》第4章 例4.6
 * 适用环境: Visual Studio / Dev-C++ / VS Code
 * 
 * 核心教学目标:
 * 1. 掌握双重 for 循环嵌套的物理执行轨迹（外层动一步，内层跑一整轮）
 * 2. 掌握左下直角三角形的数学几何约束：列号 j <= 当前行号 i
 * 3. 掌握控制台工程对齐技术：横向制表符 '\t' 与格式符 '%-2d' 左对齐
 * 
 * 矩阵坐标映射图 (Row i, Column j):
 *   i=1: [1*1]
 *   i=2: [1*2] [2*2]
 *   i=3: [1*3] [2*3] [3*3]
 *   ...
 *   i=9: [1*9] [2*9] [3*9] ... [9*9]
 */

#include <stdio.h>

int main(void)
{
    printf("========================================================================================\n");
    printf("                  经典算法实战 —— 精美九九乘法表 (双重 for 循环与制表符对齐)             \n");
    printf("========================================================================================\n\n");

    // =========================================================================
    // 【外层循环：控制矩阵的行数 (Row)】
    // 时钟模型类比: 外层犹如“分针”，i 从 1 变到 9，每动一次代表新的一行开始
    // =========================================================================
    for (int i = 1; i <= 9; i++)
    {
        // =====================================================================
        // 【内层循环：控制当前行打印的列数 (Column)】
        // 时钟模型类比: 内层犹如“秒针”，必须完整走完设定轮次，外层才能走下一步
        // 数学约束机理: j <= i。第 1 行打 1 列，第 3 行打 3 列，自然呈现左下直角三角形！
        // =====================================================================
        for (int j = 1; j <= i; j++)
        {
            // 输出细节深度解析:
            // 1. 打印 "j * i = 乘积"：按照中国人朗读习惯（如“二三得六”，2 是列 j，3 是行 i）；
            // 2. "%-2d"：左对齐占 2 位，使个位数与两位数结果（如 4 与 12）宽度一致；
            // 3. "\t"：横向制表符（Tab），强制光标对齐到下一个 8 字符边界，避免不同终端下的锯齿扭曲。
            printf("%d*%d=%-2d\t", j, i, j * i);
        }

        // ⚠️ 关键排版指令:
        // 当前行所有列打印完毕后，立刻回车换行！必须处于外层大括号内、内层大括号外。
        printf("\n");
    }

    printf("\n========================================================================================\n");
    return 0;
}
