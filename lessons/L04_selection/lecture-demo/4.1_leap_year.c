/*
 * 文件名: 4.1_leap_year.c
 * 对应课件: 第04讲 PPT 第12页【课堂案例：双书深度融合——闰年判定算法】
 * 对应教材: 谭浩强版《C程序设计》第4章 例4.8 + 何钦铭版《C语言程序设计》第2章 例2.3
 * 适用环境: Visual Studio / Dev-C++ / VS Code
 * 
 * 核心教学目标:
 * 1. 掌握公元年份闰年判定的物理数学法则：能被 4 整除但不能被 100 整除，或者能被 400 整除
 * 2. 深度对比两种编码心智模型：何版“嵌套条件逻辑树” vs 谭版“复合逻辑表达式”
 * 3. 掌握 C 语言逻辑短路求值 (Short-circuit Evaluation) 的底层运行机制
 */

#include <stdio.h>

int main(void)
{
    printf("====================================================\n");
    printf("      双书融合案例 —— 公元年份闰年判定深度解析      \n");
    printf("====================================================\n\n");

    int year = 0;
    int leap_he = 0;   // 方法1（何版嵌套逻辑树）判定结果：1代表闰年，0代表平年
    int leap_tan = 0;  // 方法2（谭版复合表达式）判定结果：1代表闰年，0代表平年

    // 1. 安全数据输入与防御性检验
    printf("请输入一个公元年份 (例如 2000, 2024, 1900): ");
    if (scanf("%d", &year) != 1 || year <= 0) {
        printf("⚠️ 输入错误: 请输入有效的正整数年份！\n");
        return 1;
    }

    // =========================================================================
    // 方案一：何版“案例驱动式”层层嵌套逻辑树 (Nested Logic Tree)
    // 优势: 逻辑层次自顶向下展开，每一步依赖关系清晰可见，极适合算法初学者理清分支。
    // =========================================================================
    if (year % 4 == 0) {
        if (year % 100 == 0) {
            if (year % 400 == 0) {
                leap_he = 1; // 能被400整除，世纪闰年（如2000年）
            } else {
                leap_he = 0; // 能被100但不能被400整除，世纪平年（如1900年）
            }
        } else {
            leap_he = 1;     // 能被4整除且不能被100整除，普通闰年（如2024年）
        }
    } else {
        leap_he = 0;         // 不能被4整除，普通平年（如2023年）
    }

    // =========================================================================
    // 方案二：谭版“复合逻辑表达式合并法” (Compound Logical Expression)
    // 优势: 代码高度紧凑，借助 && 和 || 运算符的短路求值机制，CPU 运行效率极高。
    //
    // 短路求值 (Short-circuit Evaluation) 底层机理:
    // 1. 若 (year % 4 == 0) 为假(0)，根据 && 的短路原则，后面的 (year % 100 != 0) 直接跳过不执行；
    // 2. 接着转去计算 || 右侧的 (year % 400 == 0)，若成立则判定为真(1)；
    // 3. 若 || 左侧复合项判定为真(1)，根据 || 的短路原则，右侧的 (year % 400 == 0) 直接被掐断跳过！
    // =========================================================================
    if ((year % 4 == 0 && year % 100 != 0) || (year % 400 == 0)) {
        leap_tan = 1;
    } else {
        leap_tan = 0;
    }

    // 2. 并排对比输出验证
    printf("\n---------------- 闰年判定结论对比 ----------------\n");
    printf("  测试年份 (Year)                     : %d 年\n", year);
    printf("  方法 1 [何版嵌套逻辑树] 判定结果   : %s (%d)\n", leap_he ? "🎉 闰年 (Leap Year)" : "平年 (Common Year)", leap_he);
    printf("  方法 2 [谭版复合逻辑式] 判定结果   : %s (%d)\n", leap_tan ? "🎉 闰年 (Leap Year)" : "平年 (Common Year)", leap_tan);
    printf("--------------------------------------------------\n\n");

    printf("💡 教学点拨: 方案一重在思维严密展开，方案二重在工程紧凑高效，两者物理结果完全等价！\n");
    printf("====================================================\n");

    return 0;
}
